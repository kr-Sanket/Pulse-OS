// The shared foundation every PulseOS portal builds on (ADR-003: apps stay separate at the
// routing and deploy level but share components, tokens and plumbing).
//
// What lives here is what is genuinely identical across portals: the authentication layer,
// the request-result contract, the load-once hook, the design tokens, and — since the
// hospital portal would have made a third copy — the shadcn UI primitives. What does not
// live here is each app's navigation shell and feature components, which differ by role.
//
// The primitives were byte-identical in both portals when they were hoisted, so this is one
// implementation, not a merge of two. They are generated by the shadcn CLI from this
// package's own `components.json`; run `pnpm dlx shadcn@latest add <name>` from
// `packages/ui`, never from an app, or the duplication starts again.
//
// Design tokens are a CSS entry point, not a TS export: `@import "@pulseos/ui/tokens.css"`.
// The primitives carry Tailwind utility classes, so each app must also point Tailwind at
// this package's sources — `@source "../../../packages/ui/src";` in its index.css.
// Without that the classes are never generated and the components render unstyled.

